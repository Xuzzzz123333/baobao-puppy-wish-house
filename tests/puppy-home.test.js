function fixture() {
  let actor = 'alice',moderation = 'pass',queue = Promise.resolve()
  const users = { alice:{ role:'chef',partnerOpenid:'bob',pairedAt:100 },bob:{ role:'diner',partnerOpenid:'alice',pairedAt:100 },
    eve:{ role:'chef',partnerOpenid:'other',pairedAt:200 },other:{ role:'diner',partnerOpenid:'eve',pairedAt:200 } }
  const docs = new Map()
  const clone = value => structuredClone(value)
  const collection = () => ({ doc:id => ({
    get:async () => ({ data:docs.has(id) ? { ...clone(docs.get(id)),_id:id } : null }),
    set:async ({ data }) => { assert.ok(!('_id' in data)); docs.set(id,clone(data)) },
    remove:async () => { docs.delete(id) }
  }) })
  const db = { collection,runTransaction(work) { const result = queue.then(() => work({ collection })); queue = result.catch(() => {}); return result } }
  const getPair = async (_,openid,required) => {
    const me = users[openid], partner = users[me.partnerOpenid]
    if (!partner || partner.partnerOpenid !== openid) { if (required) fail('pair_required'); return null }
    return { me,partner,otherId:me.partnerOpenid,key:[openid,me.partnerOpenid].sort().join(':') }
  }
  const context = { db,collection:'puppyWishes',getPair,readDoc:async (reader,name,id) => (await reader.collection(name).doc(id).get()).data,displayName:user => user.role === 'chef' ? '店长' : '宝宝',checkText:async () => { if (moderation !== 'pass') fail('content_review') } }
  const inbox = createInbox(context),handle = createHomeHandler(context),daily = createDailyHandler({ ...context,prepareNotice:inbox.prepare })
  return { call:event => handle(event,actor),dailyCall:event => daily(event,actor),inboxCall:event => inbox.handle(event,actor),setActor:value => { actor = value },setModeration:value => { moderation = value },users,docs }
}
