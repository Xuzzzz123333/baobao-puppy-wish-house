test('照片拒绝伪造格式和过大请求，不接受任意文件地址', () => {
  assert.equal(photoInput(jpeg).type,'jpg')
  for (const value of ['',{},'https://example.com/photo.jpg','YWJjZA==',Buffer.alloc(MAX_PHOTO_BYTES + 1).toString('base64')]) assert.throws(() => photoInput(value),/invalid_photo/)
})
function image(index,size = 7) {
  const buffer = Buffer.alloc(size,index)
  buffer[0] = 255; buffer[1] = 216; buffer[size - 2] = 255; buffer[size - 1] = 217
  return buffer.toString('base64')
}
test('相册允许追加到十张、去重、调整封面和留言；减少上限不误删照片', async () => {
  const f = fixture()
  const ids = []
  for (let index = 0; index < 10; index += 1) {
    const result = await f.call({ action:'photoAdd',image:image(index) })
    ids.push(result.album.items[index].id)
  }
  assert.equal((await f.call({ action:'homeGet' })).home.photoCount,10)
  assert.equal((await f.call({ action:'photoAdd',image:image(1) })).duplicate,true)
  await assert.rejects(f.call({ action:'photoAdd',image:image(11) }),/album_full/)
  await assert.rejects(f.call({ action:'photoLimit',limit:6 }),/album_limit_small/)
  assert.equal((await f.call({ action:'photoAlbumGet' })).photos.length,10)
  const reversed = ids.slice().reverse()
  await f.call({ action:'photoOrder',ids:reversed })
  await f.call({ action:'photoCaption',photoId:reversed[0],caption:'和你一起的普通一天' })
  assert.equal((await f.call({ action:'photoGet' })).photo.caption,'和你一起的普通一天')
  await assert.rejects(f.call({ action:'photoOrder',ids:ids.slice(0,9) }),/state_changed/)
  await assert.rejects(f.call({ action:'photoGet',photoId:'forged' }),/forbidden/)
  f.setModeration('risky')
  await assert.rejects(f.call({ action:'photoCaption',photoId:reversed[0],caption:'未通过的修改' }),/content_review/)
  assert.equal((await f.call({ action:'photoGet' })).photo.caption,'和你一起的普通一天')
  f.setModeration('pass')
  for (const id of reversed.slice(0,7)) await f.call({ action:'photoDelete',photoId:id })
  assert.equal((await f.call({ action:'photoLimit',limit:3 })).home.albumLimit,3)
  assert.equal(f.docs.size,4)
})
