const fs = require('fs')
const path = require('path')
const root = path.resolve(__dirname, '..')
const source = path.join(root, 'cloudfunctions/puppyWishes/catalog.js')
const target = path.join(root, 'data/interaction-catalog.js')
fs.copyFileSync(source, target)
fs.copyFileSync(path.join(root,'cloudfunctions/puppyWishes/notices.js'),path.join(root,'data/notices.js'))
fs.copyFileSync(path.join(root,'cloudfunctions/puppyWishes/daily-content.js'),path.join(root,'data/daily-content.js'))
const domain = fs.readFileSync(path.join(root,'cloudfunctions/puppyWishes/domain.js'),'utf8')
fs.writeFileSync(path.join(root,'data/wish-domain.js'),domain.replace("require('./catalog')","require('./interaction-catalog')"))
const keepsakes = fs.readFileSync(path.join(root,'cloudfunctions/puppyWishes/keepsakes.js'),'utf8')
fs.writeFileSync(path.join(root,'data/keepsakes.js'),keepsakes.replace("require('./domain')","require('./wish-domain')"))
console.log('互动目录与演示状态规则已同步')
